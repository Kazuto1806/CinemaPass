const restoreOriginalText = (node) => {
  if (node.__cinemaOriginalText !== undefined) {
    if (node.nodeValue !== node.__cinemaOriginalText) {
      node.nodeValue = node.__cinemaOriginalText;
    }
  }
};

const translateText = (text) => {
  const trimmed = text.trim();
  if (!trimmed) return text;

  const countMovie = trimmed.match(/^(\d+)\s+phim$/);
  if (countMovie) {
    const leading = text.slice(0, text.indexOf(trimmed));
    const trailing = text.slice(text.indexOf(trimmed) + trimmed.length);
    return `${leading}${countMovie[1]} movies${trailing}`;
  }

  const countTicket = trimmed.match(/^(\d+)\s+vé$/);
  if (countTicket) {
    const leading = text.slice(0, text.indexOf(trimmed));
    const trailing = text.slice(text.indexOf(trimmed) + trimmed.length);
    return `${leading}${countTicket[1]} tickets${trailing}`;
  }

  if (Object.prototype.hasOwnProperty.call(VN_TO_EN, trimmed)) {
    const leading = text.slice(0, text.indexOf(trimmed));
    const trailing = text.slice(text.indexOf(trimmed) + trimmed.length);
    return `${leading}${VN_TO_EN[trimmed]}${trailing}`;
  }

  let result = text;
  for (const [vn, en] of PHRASE_REPLACEMENTS) {
    result = result.replaceAll(vn, en);
  }
  return result;
};

const translateNode = (node) => {
  if (node.__cinemaOriginalText === undefined) {
    node.__cinemaOriginalText = node.nodeValue;
  }
  const translated = translateText(node.__cinemaOriginalText);
  if (node.nodeValue !== translated) {
    node.nodeValue = translated;
  }
};

const ATTRIBUTE_KEYS = ["placeholder", "title", "aria-label", "alt"];

const translateElement = (element) => {
  for (const key of ATTRIBUTE_KEYS) {
    if (!element.hasAttribute(key)) continue;

    const originalKey = `__cinemaOriginal${key}`;
    if (element[originalKey] === undefined) {
      element[originalKey] = element.getAttribute(key);
    }
    const translated = translateText(element[originalKey]);
    if (element.getAttribute(key) !== translated) {
      element.setAttribute(key, translated);
    }
  }
};

const translateSubtree = (root) => {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    translateNode(root);
    return;
  }

  if (root.nodeType === Node.ELEMENT_NODE) {
    translateElement(root);
  }

  for (const node of root.childNodes || []) {
    translateSubtree(node);
  }
};

const restoreSubtree = (root) => {
  if (!root) return;

  if (root.nodeType === Node.TEXT_NODE) {
    restoreOriginalText(root);
    return;
  }

  if (root.nodeType === Node.ELEMENT_NODE) {
    for (const key of ATTRIBUTE_KEYS) {
      const originalKey = `__cinemaOriginal${key}`;
      if (elementOriginalValue(root, originalKey) !== undefined) {
        if (root.getAttribute(key) !== root[originalKey]) {
          root.setAttribute(key, root[originalKey]);
        }
      }
    }
  }

  for (const node of root.childNodes || []) {
    restoreSubtree(node);
  }
};

const elementOriginalValue = (element, key) => element[key];

export const applyGlobalLanguage = () => {
  const language = localStorage.getItem("language") || "VN";
  document.documentElement.lang = language === "EN" ? "en" : "vi";

  if (language === "VN") {
    restoreSubtree(document.body);
  } else {
    translateSubtree(document.body);
  }
};

export const installGlobalLanguage = () => {
  applyGlobalLanguage();

  const observer = new MutationObserver((mutations) => {
    if ((localStorage.getItem("language") || "VN") !== "EN") return;

    for (const mutation of mutations) {
      if (mutation.type === "childList") {
        for (const node of mutation.addedNodes) {
          translateSubtree(node);
        }
      } else if (mutation.type === "characterData") {
        translateNode(mutation.target);
      } else if (mutation.type === "attributes") {
        translateElement(mutation.target);
      }
    }
  });

  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
  });

  window.addEventListener("languageChanged", applyGlobalLanguage);
  return () => {
    observer.disconnect();
    window.removeEventListener("languageChanged", applyGlobalLanguage);
  };
};
